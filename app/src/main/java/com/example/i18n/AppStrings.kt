object AppStrings {

    fun forLanguage(lang: AppLanguage): LocalizedStrings = when (lang) {
        AppLanguage.EN -> EN
        AppLanguage.ES -> ES
        AppLanguage.FR -> FR
        AppLanguage.DE -> DE
        AppLanguage.IT -> IT
        AppLanguage.PT -> PT
        AppLanguage.JA -> JA
        AppLanguage.KO -> KO
        AppLanguage.ZH -> ZH
        AppLanguage.HI -> HI
        AppLanguage.AR -> AR
    }

    fun difficultyName(s: LocalizedStrings, d: Difficulty): String = when (d) {
        Difficulty.EASY -> s.diffEasy
        Difficulty.NORMAL -> s.diffNormal
        Difficulty.HARD -> s.diffHard
    }

    fun biomeDesc(s: LocalizedStrings, b: Biome): String = when (b) {
        Biome.DESERT -> s.biomeDesert
        Biome.ICE -> s.biomeIce
        Biome.VOLCANO -> s.biomeVolcano
        Biome.CAVERN -> s.biomeCavern
        Biome.RUINS -> s.biomeRuins
    }

    fun rivalName(s: LocalizedStrings, r: RivalPersonality): String = when (r) {
        RivalPersonality.RUBBLE -> s.rivalRubble
        RivalPersonality.GOLDIE -> s.rivalGoldie
        RivalPersonality.VEX -> s.rivalVex
        RivalPersonality.MOSS -> s.rivalMoss
    }

    fun upgradeName(s: LocalizedStrings, u: UpgradeType): String = when (u) {
        UpgradeType.TITANIUM_PICK -> s.upgradePickName
        UpgradeType.LANTERN_OPTICS -> s.upgradeLanternName
        UpgradeType.STAMINA_FLASK -> s.upgradeStaminaName
        UpgradeType.SONAR_RIG -> s.upgradeSonarName
        UpgradeType.GEM_HARVESTER -> s.upgradeHarvesterName
        UpgradeType.BLAST_SHIELD -> s.upgradeShieldName
    }

    fun upgradeDesc(s: LocalizedStrings, u: UpgradeType): String = when (u) {
        UpgradeType.TITANIUM_PICK -> s.upgradePickDesc
        UpgradeType.LANTERN_OPTICS -> s.upgradeLanternDesc
        UpgradeType.STAMINA_FLASK -> s.upgradeStaminaDesc
        UpgradeType.SONAR_RIG -> s.upgradeSonarDesc
        UpgradeType.GEM_HARVESTER -> s.upgradeHarvesterDesc
        UpgradeType.BLAST_SHIELD -> s.upgradeShieldDesc
    }

    fun achievementLabel(s: LocalizedStrings, id: AchievementId): String = when (id) {
        AchievementId.FIRST_WIN -> s.achFirstWin
        AchievementId.GEM_HUNTER -> s.achGemHunter
        AchievementId.COMBO_MASTER -> s.achComboMaster
        AchievementId.EXPLORER -> s.achExplorer
        AchievementId.SPEEDSTER -> s.achSpeedster
        AchievementId.UPGRADE_MASTER -> s.achUpgradeMaster
    }

    fun modifierBadge(m: Modifier): String = m.wireName

    fun powerupBadge(p: PowerupType): String = p.wireName.uppercase()

